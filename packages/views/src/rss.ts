/**
 * RSS feed rendering — port of nitter's `src/views/rss.nimf` (the
 * `renderTimelineRss`/`renderListRss`/`renderSearchRss` string templates and
 * their `getTitle`/`renderRssTweet` helpers).
 *
 * Like the Nim original these are plain string templates, not TSX: the item
 * bodies are XML/RSS with a CDATA HTML payload. Tweet text arrives pre-escaped
 * from the parser (see the twitter-parser notes), so — as in nitter — it is
 * interpolated raw inside CDATA; only titles, card fields, and poll options
 * (plain-text slots) go through `escapeXml`.
 *
 * The parser port flattens threads, so `renderRssTweets` takes `Tweet[]`
 * where the Nim template takes `seq[Tweets]`; the pinned-tweet splice
 * (`getTweetsWithPinned`) runs over the flat list.
 *
 * Deliberate divergences from the Nim original (documented at the call site):
 * - `xmltree.escape` is reproduced exactly (`&`, `<`, `>`, `"`).
 * - The snowflake GUID cutoff (`2000000000000000000`) compares `BigInt` tweet
 *   ids (Nim compares int64; TS ids stay strings because they exceed
 *   `Number.MAX_SAFE_INTEGER`).
 * - `stripWhitespace(...).join(" ")` filters the empty edge segments
 *   `String.split` would otherwise keep.
 */

import type { TseerPreferences } from "@tseer/prefs";
import type { ArticlePreview, Card, List, Media, Poll, Profile, Tweet } from "@tseer/types";
import { CardKind, MediaKind } from "@tseer/types";
import {
  getRfc822Time,
  getTweetLink,
  getUrlPrefix,
  getUserPic,
  insertSep,
  replaceUrls,
  sanitizeXml,
  stripHtml,
  type UrlPrefixConfig,
} from "./formatters.ts";
import { getPicUrl } from "./media.ts";

/** Snowflake id cutoff for the RSS GUID format transition (~Dec 14 2025 UTC). */
const GUID_CUTOFF = 2000000000000000000n;

/** nitter's default avatar for multi-user feeds (no user object to depict). */
const DEFAULT_PROFILE_PIC =
  "https://abs.twimg.com/sticky/default_profile_images/default_profile.png";

/** Port of `xmltree.escape` as used by the template: `&`, `<`, `>`, `"`. */
export function escapeXml(text: string): string {
  return text
    .replaceAll("&", "&amp;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;")
    .replaceAll('"', "&quot;");
}

/** Numeric tweet-id comparison (Nim compares int64 ids; ours are strings). */
function compareIds(a: string, b: string): number {
  try {
    const x = BigInt(a);
    const y = BigInt(b);
    return x < y ? -1 : x > y ? 1 : 0;
  } catch {
    return a < b ? -1 : a > b ? 1 : 0;
  }
}

/** Port of the template's `useGlobalGuid`: new snowflakes get a bare-id GUID. */
export function isGlobalGuid(id: string): boolean {
  try {
    return BigInt(id) >= GUID_CUTOFF;
  } catch {
    return false;
  }
}

/**
 * Port of the template's `getTitle`: `Pinned:`/`RT by @`/`R to @` prefix plus
 * the whitespace-collapsed plain text — or the article title, a media label,
 * or the card title when the text is empty.
 */
export function rssTitle(tweet: Tweet, retweet: string): string {
  let prefix = "";
  if (tweet.pinned) prefix = "Pinned: ";
  else if (retweet.length > 0) prefix = `RT by @${retweet}: `;
  else if (tweet.reply.length > 0) prefix = `R to @${tweet.reply[0] ?? ""}: `;

  const collapsed = stripHtml(tweet.text)
    .split(/\s+/)
    .filter((part) => part.length > 0)
    .join(" ");
  const text = escapeXml(collapsed);

  // article tweets' text is just the article link; the title says more
  const preview = tweet.articlePreview;
  if (preview !== undefined && preview.title.length > 0) {
    return `${prefix}${escapeXml(preview.title)}`;
  }
  if (text.length > 0) return prefix + text;

  if (tweet.media.length > 0) {
    // Reachable inputs always append a label (the three media kinds are
    // exhaustive), so — as in Nim, where the card fallback only runs when
    // `result` is still empty — the card branch below never follows this one.
    let result = prefix;
    const first = tweet.media[0]?.kind;
    if (tweet.media.some((item) => item.kind !== first)) result += "Media";
    else if (first === MediaKind.photoMedia) result += "Image";
    else if (first === MediaKind.videoMedia) result += "Video";
    else if (first === MediaKind.gifMedia) result += "Gif";
    return result;
  }

  const card = tweet.card;
  if (
    card !== undefined &&
    card.kind !== CardKind.hidden &&
    card.kind !== CardKind.unknown &&
    card.title.length > 0
  ) {
    return prefix + escapeXml(card.title);
  }
  return "";
}

/** Port of the template's `getDescription`. */
export function rssDescription(desc: string, urlPrefix: string): string {
  return `Twitter feed for: ${desc}. Generated by ${urlPrefix}`;
}

/** Port of the template's `renderRssMedia`. */
export function renderRssMedia(media: Media, tweet: Tweet, urlPrefix: string): string {
  switch (media.kind) {
    case MediaKind.photoMedia: {
      const photo = media.photo;
      return `<img src="${urlPrefix}${getPicUrl(photo.url)}" style="max-width:250px;" />`;
    }
    case MediaKind.videoMedia: {
      const video = media.video;
      return `<a href="${urlPrefix}${getTweetLink(tweet)}">\n<br>Video<br>\n  <img src="${urlPrefix}${getPicUrl(video.thumb)}" style="max-width:250px;" />\n</a>`;
    }
    case MediaKind.gifMedia: {
      const gif = media.gif;
      const thumb = `${urlPrefix}${getPicUrl(gif.thumb)}`;
      const url = `${urlPrefix}${getPicUrl(gif.url)}`;
      return `<video poster="${thumb}" autoplay muted loop style="max-width:250px;">\n  <source src="${url}" type="video/mp4"></video>`;
    }
  }
}

/** Port of the template's `renderRssCard`. */
export function renderRssCard(card: Card, prefs: TseerPreferences, urlPrefix: string): string {
  const cardLink = card.url.startsWith("/") ? urlPrefix + card.url : replaceUrls(card.url, prefs);
  const title = escapeXml(card.title);
  let out = "<hr/>\n<b>Link</b><br>\n";
  if (cardLink.length > 0) out += `<a href="${escapeXml(cardLink)}">\n`;
  if (card.image.length > 0) {
    out += `<img src="${urlPrefix}${getPicUrl(card.image)}" style="max-width:250px;" />\n`;
  }
  if (title.length > 0) {
    if (card.image.length > 0) out += "<br>\n";
    out += `<b>${title}</b>\n`;
  }
  if (cardLink.length > 0) out += "</a>\n";
  if (card.text.length > 0) out += `<p>${escapeXml(card.text)}</p>\n`;
  if (cardLink.length > 0) {
    const dest = card.dest.length > 0 ? escapeXml(card.dest) : escapeXml(cardLink);
    out += `<small><a href="${escapeXml(cardLink)}">${dest}</a></small>\n`;
  } else if (card.dest.length > 0) {
    out += `<small>${escapeXml(card.dest)}</small>\n`;
  }
  return out;
}

/** Port of the template's `renderRssArticle`. */
export function renderRssArticle(article: ArticlePreview, urlPrefix: string): string {
  const link = `${urlPrefix}/i/article/${article.tweetId}`;
  let out = "<hr/>\n<b>Article</b><br>\n";
  out += `<a href="${link}">\n`;
  if (article.coverImage.length > 0) {
    out += `<img src="${urlPrefix}${getPicUrl(article.coverImage)}" style="max-width:250px;" />\n`;
  }
  if (article.title.length > 0) {
    if (article.coverImage.length > 0) out += "<br>\n";
    out += `<b>${escapeXml(article.title)}</b>\n`;
  }
  out += "</a>\n";
  if (article.previewText.length > 0) out += `<p>${escapeXml(article.previewText)}</p>\n`;
  return out;
}

/** Port of the template's `renderRssPoll`. */
export function renderRssPoll(poll: Poll): string {
  let out = "<hr/>\n<b>Poll</b>\n<p>\n";
  for (let i = 0; i < poll.options.length; i++) {
    const value = poll.values[i] ?? 0;
    const perc = poll.votes > 0 ? (value / poll.votes) * 100 : 0;
    // Nim `(&"{perc:.0f}").strip(chars={'.'})`; `toFixed(0)` never emits the dot.
    out += `${perc.toFixed(0)}% — ${escapeXml(poll.options[i] ?? "")}<br>\n`;
  }
  out += `<i>${insertSep(String(poll.votes))} votes • ${escapeXml(poll.status)}</i>\n</p>\n`;
  return out;
}

/**
 * Port of the template's `renderRssTweet` (recursive through quotes). The
 * entry unwrap (`tweet.retweet.get(tweet)`) makes a second unwrap of an
 * already-unwrapped quote tweet idempotent.
 */
export function renderRssTweet(tweet: Tweet, prefs: TseerPreferences, urlPrefix: string): string {
  const shown = tweet.retweet ?? tweet;
  let out = "";
  const text = replaceUrls(shown.text, prefs, urlPrefix);
  if (text.length > 0) out += `<p>${text.replaceAll("\n", "<br>\n")}</p>\n`;
  if (shown.media.length > 0) {
    for (const media of shown.media) out += `${renderRssMedia(media, shown, urlPrefix)}\n`;
  } else if (
    shown.card !== undefined &&
    shown.card.kind !== CardKind.hidden &&
    shown.card.kind !== CardKind.unknown
  ) {
    out += `${renderRssCard(shown.card, prefs, urlPrefix)}\n`;
  }
  if (shown.articlePreview !== undefined) {
    out += `${renderRssArticle(shown.articlePreview, urlPrefix)}\n`;
  }
  if (shown.poll !== undefined) out += `${renderRssPoll(shown.poll)}\n`;
  if (shown.note.length > 0 && !prefs.hideCommunityNotes) {
    out += `<p><b>Community note:</b> ${replaceUrls(shown.note, prefs, urlPrefix)}</p>\n`;
  }
  const quote = shown.quote;
  if (quote !== undefined && quote.available) {
    const quoteLink = urlPrefix + getTweetLink(quote);
    out += `<hr/>\n<blockquote>\n<b>${quote.user.fullname} (@${quote.user.username})</b>\n<p>\n${renderRssTweet(quote, prefs, urlPrefix)}\n</p>\n<footer>\n— <cite><a href="${quoteLink}">${quoteLink}</a>\n</footer>\n</blockquote>\n`;
  }
  return out;
}

/**
 * Port of the template's `renderRssTweets`: deduped items over the flat tweet
 * list, skipping other users' tweets when a profile id is given (the check
 * runs on the *outer* tweet, so the profile owner's retweets stay included).
 */
export function renderRssTweets(
  tweets: Tweet[],
  prefs: TseerPreferences,
  urlPrefix: string,
  userId = "",
): string {
  let out = "";
  const links: string[] = [];
  for (const tweet of tweets) {
    if (userId.length > 0 && tweet.user.id !== userId) continue;

    const retweet = tweet.retweet !== undefined ? tweet.user.username : "";
    const shown = tweet.retweet ?? tweet;
    const link = getTweetLink(shown);
    if (links.includes(link)) continue;
    links.push(link);
    // Nim `.strip(chars={'\n'})`: only the edge newlines go.
    const body = renderRssTweet(shown, prefs, urlPrefix).replace(/^\n+|\n+$/g, "");
    out += `      <item>\n        <title>${rssTitle(shown, retweet)}</title>\n        <dc:creator>@${shown.user.username}</dc:creator>\n        <description><![CDATA[${body}]]></description>\n        <pubDate>${getRfc822Time(shown.time)}</pubDate>\n`;
    if (isGlobalGuid(shown.id)) out += `        <guid isPermaLink="false">${shown.id}</guid>\n`;
    else out += `        <guid>${urlPrefix}${link}</guid>\n`;
    out += `        <link>${urlPrefix}${link}</link>\n      </item>\n`;
  }
  return out;
}

/**
 * Port of the template's `getTweetsWithPinned`: splice the pinned tweet ahead
 * of the first older tweet (Nim compares int64 ids; `compareIds` does). When
 * every tweet is newer the pin stays out, exactly like the Nim loops.
 */
export function withPinned(content: Tweet[], pinned?: Tweet): Tweet[] {
  const result = [...content];
  if (pinned !== undefined && result.length > 0) {
    for (let i = 0; i < result.length; i++) {
      if (compareIds(result[i]?.id ?? "", pinned.id) < 0) {
        result.splice(i, 0, pinned);
        break;
      }
    }
  }
  return result;
}

/** The multi-user stub avatar (rss.nim `timelineRss`). */
export function defaultProfilePic(): string {
  return DEFAULT_PROFILE_PIC;
}

/** Port of the template's `renderTimelineRss`. */
export function renderTimelineRss(
  profile: Profile,
  cfg: UrlPrefixConfig,
  prefs: TseerPreferences,
  multi = false,
): string {
  const urlPrefix = getUrlPrefix(cfg);
  const handle = `${multi ? "" : "@"}${profile.user.username}`;
  let title = profile.user.fullname;
  if (!multi) title += ` / ${handle}`;
  title = sanitizeXml(escapeXml(title));
  let out = `<?xml version="1.0" encoding="UTF-8"?>\n<rss xmlns:atom="http://www.w3.org/2005/Atom" xmlns:dc="http://purl.org/dc/elements/1.1/" version="2.0">\n  <channel>\n    <atom:link href="${urlPrefix}/${profile.user.username}/rss" rel="self" type="application/rss+xml" />\n    <title>${title}</title>\n    <link>${urlPrefix}/${profile.user.username}</link>\n    <description>${rssDescription(handle, urlPrefix)}</description>\n    <language>en-us</language>\n    <ttl>40</ttl>\n    <image>\n      <title>${title}</title>\n      <link>${urlPrefix}/${profile.user.username}</link>\n      <url>${urlPrefix}${getPicUrl(getUserPic(profile.user.userPic, "_400x400"))}</url>\n      <width>128</width>\n      <height>128</height>\n    </image>\n`;
  const tweets = withPinned(profile.tweets.content, profile.pinned);
  if (tweets.length > 0) out += renderRssTweets(tweets, prefs, urlPrefix, profile.user.id);
  out += "  </channel>\n</rss>\n";
  return out;
}

/** Port of the template's `renderListRss`. */
export function renderListRss(
  tweets: Tweet[],
  list: List,
  cfg: UrlPrefixConfig,
  prefs: TseerPreferences,
): string {
  const urlPrefix = getUrlPrefix(cfg);
  const link = `${urlPrefix}/i/lists/${list.id}`;
  let out = `<?xml version="1.0" encoding="UTF-8"?>\n<rss xmlns:atom="http://www.w3.org/2005/Atom" xmlns:dc="http://purl.org/dc/elements/1.1/" version="2.0">\n  <channel>\n    <atom:link href="${link}" rel="self" type="application/rss+xml" />\n    <title>${escapeXml(list.name)} / @${list.username}</title>\n    <link>${link}</link>\n    <description>${rssDescription(`${list.name} by @${list.username}`, urlPrefix)}</description>\n    <language>en-us</language>\n    <ttl>40</ttl>\n`;
  out += renderRssTweets(tweets, prefs, urlPrefix);
  out += " </channel>\n</rss>\n";
  return out;
}

/** Port of the template's `renderSearchRss` (`param` is unused upstream too). */
export function renderSearchRss(
  tweets: Tweet[],
  name: string,
  _param: string,
  cfg: UrlPrefixConfig,
  prefs: TseerPreferences,
): string {
  const urlPrefix = getUrlPrefix(cfg);
  const link = `${urlPrefix}/search`;
  const escName = escapeXml(name);
  let out = `<?xml version="1.0" encoding="UTF-8"?>\n<rss xmlns:atom="http://www.w3.org/2005/Atom" xmlns:dc="http://purl.org/dc/elements/1.1/" version="2.0">\n  <channel>\n    <atom:link href="${link}" rel="self" type="application/rss+xml" />\n    <title>Search results for "${escName}"</title>\n    <link>${link}</link>\n    <description>${rssDescription(`Search "${escName}"`, urlPrefix)}</description>\n    <language>en-us</language>\n    <ttl>40</ttl>\n`;
  out += renderRssTweets(tweets, prefs, urlPrefix);
  out += "  </channel>\n</rss>\n";
  return out;
}
