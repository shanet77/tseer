/**
 * The `/pic` + `/video` routes — port of nitter `src/routes/media.nim`.
 *
 * Structure differs from upstream in one way that matters: nitter expresses each
 * route as a regex with an *optional* `(enc)?` group and re-derives the encoding
 * by testing whether that group matched. Here each encoding is its own registered
 * route, so the handler knows the encoding by construction and the `:url`
 * parameter arrives already percent-decoded by fastify (never decoded twice —
 * see `decodeUrl`'s note in `urls.ts`).
 *
 * The security-relevant invariants, all preserved from nitter:
 * - `/video/` requires a valid HMAC for the decoded URL. `/pic/` does not,
 *   because those links are embedded in rendered HTML.
 * - Every fetched URL is checked against the twitter-domain allowlist, *again*,
 *   after decoding. Decoding is attacker-controlled, so the check cannot be
 *   skipped even though the link was generated by us.
 * - Amplify video playlists are rejected (`/amplify_video/`), matching nitter.
 */
import type { AppReply, AppRequest, HttpServer } from "@tseer/server";
import type { Context } from "cordis";
import { UndiciMediaFetcher } from "./fetcher.ts";
import { getM3u8Url, PROXYABLE_EXTENSIONS, proxifyVideo } from "./hls.ts";
import { collect, DEFAULT_CACHE_CONTROL, proxyMedia } from "./proxy.ts";
import type { MediaFetcher, MediaRoutePluginOptions, MediaSigner } from "./types.ts";
import { decodeSegment, isTwitterUrl, normalizeImgUrl, type SegmentEncoding } from "./urls.ts";

/** `m3u8Mime` from `routes/media.nim`. */
const M3U8_MIME = "application/vnd.apple.mpegurl";

/** Playlist extensions handled by rewriting rather than byte-proxying. */
const MANIFEST_EXTENSIONS = [".vmap", ".m3u8"];

/** nitter refuses amplify-video playlists on the media route. */
const AMPLIFY_MARKER = "/amplify_video/";

/** Per-request dependencies the handlers need from the plugin closure. */
interface HandlerDeps {
  media: MediaSigner;
  fetcher: MediaFetcher;
  proxyVideos: boolean;
  maxAttempts: number | undefined;
  headersTimeoutMs: number | undefined;
  cacheControl: string;
  onRetry: ((message: string) => void) | undefined;
}

function hasExtension(url: string, extensions: string[]): boolean {
  return extensions.some((ext) => url.includes(ext));
}

/** nitter's `resp` for a bare status code. */
function fail(reply: AppReply, status: number): void {
  reply.text("", { status });
}

/**
 * Read the encoded URL out of a matched route.
 *
 * `params.url` is already percent-decoded by fastify, so the `percent` case
 * needs no work — and must not be decoded again (see `decodeSegment`). The
 * `enc` case still has its base64 to undo.
 */
function readUrl(req: AppRequest, encoding: SegmentEncoding): string {
  return decodeSegment(req.params["url"] ?? "", encoding);
}

/**
 * Headers forwarded with a byte-for-byte proxied body.
 *
 * `content-length` is included and `cache-control`/`etag` come from upstream when
 * present, overriding our defaults — nitter rewrites all four headers too, but
 * with its own hash; ours are computed in `proxyMedia`.
 */
function passthroughHeaders(headers: Record<string, string>, cacheControl: string) {
  const out: Record<string, string> = {
    "cache-control": headers["cache-control"] ?? cacheControl,
  };
  const etag = headers["etag"];
  if (etag !== undefined) out["etag"] = etag;
  // Only a bare integer is forwarded: a chunked or `multipart/…` value would
  // describe framing we are not reproducing.
  const length = headers["content-length"];
  if (length !== undefined && /^\d+$/.test(length)) out["content-length"] = length;
  return out;
}

/**
 * Send an upstream body, streaming when the provider supports it.
 *
 * Only used for bodies we pass through unchanged, so the upstream framing in
 * `options.headers` still describes the bytes we emit. Rewritten playlists go
 * through `reply.send` instead, because their length no longer matches.
 */
async function streamBody(
  reply: AppReply,
  body: AsyncIterable<Uint8Array>,
  contentType: string,
  options: { status?: number | undefined; headers?: Record<string, string> | undefined },
): Promise<void> {
  if (reply.stream) {
    await reply.stream(body, contentType, options);
    return;
  }
  // Provider cannot stream (optional seam method): fall back to buffering.
  await reply.send(await collect(body), contentType, options);
}

/**
 * Serve `/pic/<enc-or-percent>/:url` (and the `/pic/orig/…` variant).
 *
 * `original` appends `?name=orig` so twimg returns the unscaled asset. That is
 * on the *fetch* URL only — the ETag stays keyed to the requested URL, as in
 * nitter.
 */
async function servePic(
  req: AppRequest,
  reply: AppReply,
  deps: HandlerDeps,
  encoding: SegmentEncoding,
  original: boolean,
): Promise<void> {
  const raw = readUrl(req, encoding);
  if (raw.length === 0 || raw.includes(AMPLIFY_MARKER)) return fail(reply, 404);

  let url = normalizeImgUrl(raw);
  if (original) url = `${url}?name=orig`;

  // The allowlist is checked *after* normalization, since `normalizeImgUrl`
  // synthesizes the `pbs.twimg.com` host for bare paths.
  if (!isTwitterUrl(url)) return fail(reply, 404);

  const result = await proxyMedia(url, {
    fetcher: deps.fetcher,
    maxAttempts: deps.maxAttempts,
    headersTimeoutMs: deps.headersTimeoutMs,
    cacheControl: deps.cacheControl,
    onRetry: deps.onRetry,
  });
  if (!result.ok) return fail(reply, result.status);

  // Revalidation: a matching If-None-Match is a 304 with no body.
  if (req.headers["if-none-match"] === result.etag) {
    result.abort();
    return reply.text("", {
      status: 304,
      headers: { etag: result.etag, "cache-control": deps.cacheControl },
    });
  }

  const contentType = result.headers["content-type"] ?? "application/octet-stream";
  await streamBody(reply, result.body, contentType, {
    status: 200,
    headers: passthroughHeaders(result.headers, deps.cacheControl),
  });
}

/**
 * Fetch a playlist body as text (nitter's `safeFetch`).
 *
 * Swallows every failure and yields `""` — a dead manifest is an empty playlist,
 * not a 500. The allowlist is re-checked here because this is a second,
 * separately-controlled fetch: a `.vmap` resolves to a *different* URL than the
 * one that was signed.
 */
async function safeFetchText(url: string, deps: HandlerDeps): Promise<string> {
  if (!isTwitterUrl(url)) return "";
  const result = await proxyMedia(url, {
    fetcher: deps.fetcher,
    maxAttempts: deps.maxAttempts,
    headersTimeoutMs: deps.headersTimeoutMs,
    onRetry: deps.onRetry,
  });
  if (!result.ok) return "";
  try {
    return (await collect(result.body)).toString("utf8");
  } catch {
    return "";
  }
}

/**
 * Serve `/video/(enc)?/:sig/:url` — the signed route.
 *
 * Three shapes, checked in nitter's order:
 * - A media segment (`.mp4`/`.ts`/`.m4s`/`.aac`) is proxied byte-for-byte.
 * - A `.vmap` is resolved to its `.m3u8`, then handled as a playlist.
 * - A `.m3u8` is fetched, its segment URLs rewritten through this instance, and
 *   returned as `application/vnd.apple.mpegurl`.
 *
 * Playlists are sent as text rather than streamed: a rewritten manifest no longer
 * matches its upstream `content-length`, so it has to be re-framed anyway, and
 * the rewrite already happens in memory. This is the only place the package
 * buffers, and it is bounded by playlist size (kilobytes), not segment size
 * (megabytes).
 */
async function serveVideo(
  req: AppRequest,
  reply: AppReply,
  deps: HandlerDeps,
  encoding: SegmentEncoding,
): Promise<void> {
  const url = readUrl(req, encoding);
  if (!isTwitterUrl(url)) return fail(reply, 403);

  const signature = req.params["sig"] ?? "";
  if (!deps.media.verify(url, signature)) return fail(reply, 403);

  if (PROXYABLE_EXTENSIONS.test(url)) {
    const result = await proxyMedia(url, {
      fetcher: deps.fetcher,
      maxAttempts: deps.maxAttempts,
      headersTimeoutMs: deps.headersTimeoutMs,
      cacheControl: deps.cacheControl,
      onRetry: deps.onRetry,
    });
    if (!result.ok) return fail(reply, result.status);
    if (req.headers["if-none-match"] === result.etag) {
      result.abort();
      return reply.text("", {
        status: 304,
        headers: { etag: result.etag, "cache-control": deps.cacheControl },
      });
    }
    const contentType = result.headers["content-type"] ?? "application/octet-stream";
    await streamBody(reply, result.body, contentType, {
      status: 200,
      headers: passthroughHeaders(result.headers, deps.cacheControl),
    });
    return;
  }

  if (hasExtension(url, MANIFEST_EXTENSIONS)) {
    // `.vmap` is an indirection: follow it to the manifest, then sign *that* URL
    // for the rewritten segments, so each link we emit is independently valid.
    let manifestUrl = url;
    if (url.includes(".vmap")) {
      const resolved = getM3u8Url(await safeFetchText(url, deps));
      if (resolved.length === 0) return fail(reply, 404);
      manifestUrl = resolved;
    }
    const playlist = await safeFetchText(manifestUrl, deps);
    if (playlist.length === 0) return fail(reply, 404);

    const rewritten = proxifyVideo(playlist, {
      proxy: deps.proxyVideos,
      manifestUrl,
      vidUrl: (target) => deps.media.vidUrl(target),
    });
    await reply.send(rewritten, M3U8_MIME, {
      status: 200,
      headers: { "cache-control": deps.cacheControl },
    });
    return;
  }

  fail(reply, 404);
}
/** Codec used by each registered media path, mirroring the link `MediaSigner` emits. */
interface PicRoute {
  encoding: SegmentEncoding;
  original: boolean;
  path: string;
}

/**
 * `/pic` paths, longest-prefix first.
 *
 * fastify's radix router gives static segments precedence over params, so
 * `/pic/orig/:url` wins over `/pic/:url` without ordering games — but both are
 * registered explicitly because each encoding is a distinct path, which is what
 * lets a handler know the encoding instead of guessing it.
 */
const PIC_ROUTES: PicRoute[] = [
  { path: "/pic/orig/enc/:url", encoding: "enc", original: true },
  { path: "/pic/orig/:url", encoding: "percent", original: true },
  { path: "/pic/enc/:url", encoding: "enc", original: false },
  { path: "/pic/:url", encoding: "percent", original: false },
];

/** `/video` paths: the signature segment comes first, then the encoded URL. */
const VIDEO_ROUTES: { path: string; encoding: SegmentEncoding }[] = [
  { path: "/video/enc/:sig/:url", encoding: "enc" },
  { path: "/video/:sig/:url", encoding: "percent" },
];

/** Register `/pic`, `/pic/orig`, and `/video` in their encoding variants. */
function registerRoutes(server: HttpServer, deps: HandlerDeps): () => void {
  const disposers = [
    // nitter's `get "/pic/?"` → `resp Http404`: the bare prefix serves nothing.
    server.route({ method: "GET", path: "/pic", handler: (_req, reply) => fail(reply, 404) }),
    ...PIC_ROUTES.map((route) =>
      server.route({
        method: "GET",
        path: route.path,
        handler: (req, reply) => servePic(req, reply, deps, route.encoding, route.original),
      }),
    ),
    ...VIDEO_ROUTES.map((route) =>
      server.route({
        method: "GET",
        path: route.path,
        handler: (req, reply) => serveVideo(req, reply, deps, route.encoding),
      }),
    ),
  ];
  return () => {
    for (const dispose of disposers) dispose();
  };
}

/**
 * Mount the media proxy routes.
 *
 * Requires `ctx.server` (to register) and `ctx.media` (to verify signatures).
 * Signing is a separate plugin so `views` can depend on `ctx.media` without
 * mounting the proxy.
 */
export default function mediaRoutePlugin(
  ctx: Context,
  options: MediaRoutePluginOptions = {},
): () => void {
  const server = ctx.get("server") as HttpServer | undefined;
  if (!server) throw new Error("media: ctx.server is not mounted (load serverPlugin first)");
  const media = ctx.get("media") as MediaSigner | undefined;
  if (!media) throw new Error("media: ctx.media is not mounted (load mediaPlugin first)");

  // A caller-supplied fetcher is the caller's to close; only one we build here
  // is ours to tear down.
  const fetcher = options.fetcher ?? new UndiciMediaFetcher(options);
  const disposeFetcher = options.fetcher === undefined ? () => void fetcher.close() : undefined;

  const deps: HandlerDeps = {
    media,
    fetcher,
    proxyVideos: options.proxyVideos ?? true,
    maxAttempts: options.maxAttempts,
    headersTimeoutMs: options.headersTimeoutMs,
    cacheControl: options.cacheControl ?? DEFAULT_CACHE_CONTROL,
    onRetry: (message) => ctx.logger.debug(message),
  };

  const disposeRoutes = registerRoutes(server, deps);
  const disposeEffect = ctx.effect(() => () => {
    disposeRoutes();
    disposeFetcher?.();
  });
  return () => {
    disposeRoutes();
    disposeFetcher?.();
    void disposeEffect();
  };
}

mediaRoutePlugin.inject = ["server", "media"];
